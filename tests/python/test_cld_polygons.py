"""CF-T5a/b: fixed CF-T4 expectations and pure decoder checks.

The JSON predates the decoder. Neither expected views nor rejection codes
are generated by production code. Extended sweeps live in
test_cld_polygon_conformance.py; both readers must match these fixed views.
"""

import hashlib
import json
import struct
import subprocess
import sys
from pathlib import Path

import pytest

from tests import cld_polygon_wire_oracle as oracle
from tools.pipeline.decoders.ps2_cld_polygons import CollisionPolygonError, decode_polygons

_VECTORS_PATH = (
    Path(__file__).resolve().parents[1] / "fixtures/synthetic/collision-polygons-v1.json"
)
_VECTORS_SHA256 = "f9218e872e29383dca73b03b895d746c991ee9c7e282d01de82a3863c1eb6b42"
_VECTORS = json.loads(_VECTORS_PATH.read_bytes())


def _wire(case):
    source = case["input"]
    raw = bytes.fromhex(source["wire_hex"])
    assert len(raw) == source["size"]
    assert hashlib.sha256(raw).hexdigest() == source["sha256"]
    return raw


def _assert_view(actual, expected):
    """Exact keys, types and values, including the sign of floating zero."""
    assert type(actual) is type(expected)
    if isinstance(expected, dict):
        assert actual.keys() == expected.keys()
        for key, value in expected.items():
            _assert_view(actual[key], value)
    elif isinstance(expected, list):
        assert len(actual) == len(expected)
        for left, right in zip(actual, expected, strict=True):
            _assert_view(left, right)
    elif isinstance(expected, float):
        assert actual.hex() == expected.hex()
    else:
        assert actual == expected


def test_conformance_inventory_is_the_unchanged_cf_t4_fixture():
    assert hashlib.sha256(_VECTORS_PATH.read_bytes()).hexdigest() == _VECTORS_SHA256
    assert _VECTORS["profile"] == "ps2-cld-polygons-v1"
    assert len(_VECTORS["fixtures"]) == 2
    assert len(_VECTORS["cases"]) == 50
    assert sum(c["expect"] == "accept" for c in _VECTORS["cases"]) == 10
    assert sum(c["expect"] == "reject" for c in _VECTORS["cases"]) == 40


@pytest.mark.parametrize("case", _VECTORS["fixtures"], ids=lambda case: case["id"])
def test_base_views_match_every_fixed_value_and_type(case):
    _assert_view(decode_polygons(_wire(case)), case["expected"])
    _assert_view(oracle.observe(_wire(case)), case["expected"])


@pytest.mark.parametrize("case", _VECTORS["cases"], ids=lambda case: case["id"])
def test_fixed_conformance_vectors(case):
    raw = _wire(case)
    if case["expect"] == "accept":
        _assert_view(decode_polygons(raw), case["expected"])
        _assert_view(oracle.observe(raw), case["expected"])
    else:
        with pytest.raises(CollisionPolygonError) as caught:
            decode_polygons(raw)
        assert isinstance(caught.value, ValueError)
        assert caught.value.code == str(caught.value) == case["expected_code"]
        assert caught.value.args == (case["expected_code"],)
        with pytest.raises(oracle.PolygonOracleError) as reference:
            oracle.observe(raw)
        assert reference.value.code == str(reference.value) == case["expected_code"]


class _BytesSubclass(bytes):
    pass


class _CoercionTrap:
    def __bytes__(self):
        raise AssertionError("The decoder must not coerce an input")

    def __len__(self):
        raise AssertionError("The type check must precede reading length")


@pytest.mark.parametrize(
    "bad",
    [
        None,
        True,
        752,
        "buffer",
        [],
        bytearray(752),
        memoryview(bytes(752)),
        _BytesSubclass(bytes(752)),
        _CoercionTrap(),
    ],
    ids=["none", "bool", "int", "str", "list", "bytearray", "memoryview", "subclass", "coercion"],
)
def test_rejects_non_exact_bytes_before_coercion_or_length(bad):
    with pytest.raises(CollisionPolygonError) as caught:
        decode_polygons(bad)
    assert caught.value.code == str(caught.value) == "CP_INPUT"


def _unreferenced_polygons(counts):
    """Own zero-coordinate shapes and empty lists; no production constants."""
    blocks = []
    for count in counts:
        blocks.append((b"\x01" + bytes(79)) * count + bytes(80))
    blocks.append(bytes(48))
    header = bytearray(384)
    struct.pack_into("<5I", header, 8, *(len(block) for block in blocks))
    struct.pack_into("<80I", header, 32, *([372] * 80))
    struct.pack_into("<I", header, 372, 0xFFFFFFFF)
    position = 384
    for group, block in enumerate(blocks):
        struct.pack_into("<I", header, 352 + group * 4, position)
        position += len(block)
    return bytes(header) + b"".join(blocks)


@pytest.mark.parametrize(
    "counts,accepted",
    [
        ((512, 0, 0, 0), True),
        ((513, 0, 0, 0), False),
        ((512, 256, 0, 0), True),
        ((512, 257, 0, 0), False),
    ],
)
def test_polygon_budgets_before_record_expansion(counts, accepted):
    raw = _unreferenced_polygons(counts)
    if accepted:
        value = decode_polygons(raw)
        assert [len(g["records"]) for g in value["groups"]] == [*counts, 0]
        assert all(c["indices"] == [] for g in value["groups"] for c in g["cells"])
    else:
        with pytest.raises(CollisionPolygonError) as caught:
            decode_polygons(raw)
        assert caught.value.code == "CP_POLYGON_BUDGET"


def test_size_limit_precedes_invalid_header():
    with pytest.raises(CollisionPolygonError) as caught:
        decode_polygons(bytes(65537))
    assert caught.value.code == "CP_SIZE"


def test_mutating_output_leaves_wire_aliases_and_later_calls_unchanged():
    case = _VECTORS["fixtures"][0]
    raw = _wire(case)
    before = hashlib.sha256(raw).digest()
    first = decode_polygons(raw)
    second = decode_polygons(raw)
    cells = first["groups"][0]["cells"]
    cells[0]["indices"].clear()
    assert cells[1]["indices"] == [1, 0, 1]
    assert cells[2]["indices"] == [1]
    cells[3]["indices"].append(1)
    assert cells[4]["indices"] == []
    first["groups"][0]["records"][0]["vector_words"][0][0] = 0
    first["groups"][0]["records"][0]["vectors_xyzw"][0][0] = 123.0
    first["origin_words"].clear()
    first["data_offsets"].clear()
    _assert_view(second, case["expected"])
    with pytest.raises(CollisionPolygonError):
        decode_polygons(b"")
    _assert_view(decode_polygons(raw), case["expected"])
    assert hashlib.sha256(raw).digest() == before


def test_fixed_vectors_keep_values_and_errors_under_python_optimization():
    # Parent assertions remain active; the child only runs the decoder under -O.
    script = """
import json, sys
from pathlib import Path
from tools.pipeline.decoders.ps2_cld_polygons import CollisionPolygonError, decode_polygons
vectors = json.loads(Path(sys.argv[1]).read_bytes())
results = []
for case in vectors['fixtures'] + vectors['cases']:
    try:
        value = decode_polygons(bytes.fromhex(case['input']['wire_hex']))
    except CollisionPolygonError as error:
        results.append({'code': error.code, 'message': str(error)})
    else:
        results.append({'value': value})
print(json.dumps(results, allow_nan=False))
"""
    result = subprocess.run(
        [sys.executable, "-O", "-c", script, str(_VECTORS_PATH)],
        capture_output=True,
        text=True,
        cwd=Path(__file__).resolve().parents[2],
        timeout=10,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    expected = [
        {"code": case["expected_code"], "message": case["expected_code"]}
        if case.get("expect") == "reject"
        else {"value": case["expected"]}
        for case in _VECTORS["fixtures"] + _VECTORS["cases"]
    ]
    _assert_view(json.loads(result.stdout), expected)
